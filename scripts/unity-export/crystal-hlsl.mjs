// The chimes' faceted crystal for the Unity port's Surface shader (issue #264): src/crystal-shader.js CRYSTAL_GLSL, the very
// GLSL the web draws, turned into HLSL and written to unity/Hiraeth/Assets/Hiraeth/Shaders/CrystalSurface.hlsl, which
// Surface.shader's HIRAETH_FIGHT variant includes (the material's _CrystalOn). Its uniforms are the material's _SkinData slots
// (engine/foe-pack.js CRYSTAL_LAYOUT); its varyings Surface.shader sets: aCrystal in the form's slot, the crystal's own beat
// in the fold's. tests/engine-unity.test.js checks the file is what this makes of the current GLSL.
//   node scripts/unity-export/crystal-hlsl.mjs          (writes it)
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { CRYSTAL_GLSL } from '../../src/crystal-shader.js';
import { CRYSTAL_LAYOUT } from '../../engine/foe-pack.js';
import { calls, RESERVED } from './skin-hlsl.mjs';

export const CRYSTAL_HLSL_PATH = fileURLToPath(new URL('../../unity/Hiraeth/Assets/Hiraeth/Shaders/CrystalSurface.hlsl', import.meta.url));

const HOST = { vCrystalBeat: 'crBeat', vCrystalGlow: 'crGlow', vCrystal: 'crCrystal', vWorldRel: 'crWorldRel', vObjRel: 'crObjRel', vObjPos: 'crObjPos', vObjNormal: 'crObjNormal',
  uTime: '_MTime', uNight: '_Night', uToon: '_Toon', uSunDir: '_SunDir' };

/** CRYSTAL_GLSL in HLSL. */
export function crystalHlsl(glsl = CRYSTAL_GLSL) {
  let s = glsl.replace(/^\s*#ifdef CHIME_CRYSTAL\s*\n/, '').replace(/\n\s*#endif\s*$/, '\n');
  if (/#/.test(s)) throw new Error('crystal-hlsl: a preprocessor line left');
  // (the varyings and uniforms' declarations: Surface.shader's and the buffer's)
  s = s.replace(/^\s*in\s+\w+\s+\w+;.*\n/gm, '').replace(/^\s*uniform\s+\w+\s+\w+;.*\n/gm, '');
  for (const t of ['vec2', 'vec3', 'vec4']) s = calls(s, t, (a) => (a.length === 1 ? `((${t})(${a[0]}))` : `${t}(${a.join(', ')})`));
  s = calls(s, 'atan', (a) => (a.length === 2 ? `atan2(${a[0]}, ${a[1]})` : `atan(${a[0]})`));
  s = s.replace(/\bvec([234])\b/g, 'float$1').replace(/\bmix\s*\(/g, 'lerp(').replace(/\bfract\s*\(/g, 'frac(');
  for (const e of CRYSTAL_LAYOUT) {
    const at = `_SkinData[${e.slot}]`;
    const v = e.type === 'float' ? `${at}.x` : e.type === 'vec2' ? `${at}.xy` : e.type === 'vec3' ? `${at}.xyz` : at;
    s = s.replace(new RegExp(`\\b${e.name}\\b`, 'g'), `(${v})`);
  }
  for (const [k, v] of Object.entries(HOST)) s = s.replace(new RegExp(`\\b${k}\\b`, 'g'), v);
  s = s.split('\n').map((l) => { const c = l.indexOf('//'), code = c < 0 ? l : l.slice(0, c); return code.replace(/\b\w+\b/g, (w) => (RESERVED.has(w) ? `${w}_` : w)) + (c < 0 ? '' : l.slice(c)); }).join('\n');
  const left = s.replace(/\/\/.*$/gm, '').match(/\bu[A-Z]\w*|\bv[A-Z]\w*/);
  if (left) throw new Error(`crystal-hlsl: a uniform or varying left: ${left[0]}`);
  return `// GENERATED by scripts/unity-export/crystal-hlsl.mjs from src/crystal-shader.js CRYSTAL_GLSL: do not edit.
// The chimes' faceted crystal (its facets, seam, edges, inner glow and lines, rim, sparkle) for Surface.shader's HIRAETH_FIGHT
// variant (the material's _CrystalOn): the web's GLSL in HLSL, three's frame throughout, its uniforms the material's
// _SkinData slots (engine/foe-pack.js CRYSTAL_LAYOUT).
#ifndef HIRAETH_CRYSTAL_SURFACE_INCLUDED
#define HIRAETH_CRYSTAL_SURFACE_INCLUDED

// (set by Surface.shader before the call: the web's varyings; crGlow its tier's glow, which the instances do not carry: 0)
static float4 crCrystal;
static float crBeat, crGlow;
static float3 crWorldRel, crObjRel, crObjPos, crObjNormal;
${s}
#endif
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(CRYSTAL_HLSL_PATH, crystalHlsl());
  console.log(CRYSTAL_HLSL_PATH);
}
