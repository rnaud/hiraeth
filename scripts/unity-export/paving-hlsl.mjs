// The paving's flagstones for the Unity port's Surface shader (issue #669): src/paving-shader.js PAVING_GLSL, the very GLSL
// the web draws, turned into HLSL and written to unity/Hiraeth/Assets/Hiraeth/Shaders/Paving.hlsl, which Surface.shader
// includes and calls on a paved material's upward faces (its _Paving: course, wear, tone, turn). tests/engine-unity.test.js
// checks the file is what this makes of the current GLSL.
//   node scripts/unity-export/paving-hlsl.mjs          (writes it)
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { PAVING_GLSL } from '../../src/paving-shader.js';
import { calls, RESERVED } from './skin-hlsl.mjs';

export const PAVING_HLSL_PATH = fileURLToPath(new URL('../../unity/Hiraeth/Assets/Hiraeth/Shaders/Paving.hlsl', import.meta.url));

const HOST = { uPaving: '_Paving', uPixelRatio: '_PixelRatio', uWearLite: '_WearLite' };

/** PAVING_GLSL in HLSL. */
export function pavingHlsl(glsl = PAVING_GLSL) {
  let s = glsl;
  if (/#/.test(s)) throw new Error('paving-hlsl: a preprocessor line in the GLSL');
  for (const t of ['vec2', 'vec3', 'vec4']) s = calls(s, t, (a) => (a.length === 1 ? `((${t})(${a[0]}))` : `${t}(${a.join(', ')})`));
  s = calls(s, 'atan', (a) => (a.length === 2 ? `atan2(${a[0]}, ${a[1]})` : `atan(${a[0]})`));
  s = s.replace(/\bvec([234])\b/g, 'float$1').replace(/\bmix\s*\(/g, 'lerp(').replace(/\bfract\s*\(/g, 'frac(');
  for (const [k, v] of Object.entries(HOST)) s = s.replace(new RegExp(`\\b${k}\\b`, 'g'), v);
  s = s.split('\n').map((l) => { const c = l.indexOf('//'), code = c < 0 ? l : l.slice(0, c); return code.replace(/\b\w+\b/g, (w) => (RESERVED.has(w) ? `${w}_` : w)) + (c < 0 ? '' : l.slice(c)); }).join('\n');
  const left = s.replace(/\/\/.*$/gm, '').match(/\bu[A-Z]\w*|\bv[A-Z]\w*/);
  if (left) throw new Error(`paving-hlsl: a uniform or varying left: ${left[0]}`);
  return `// GENERATED by scripts/unity-export/paving-hlsl.mjs from src/paving-shader.js PAVING_GLSL: do not edit.
// The plazas' and streets' flagstones (issue #669: courses, stones, worn corners, tones, cracks, grit, pits, brass discs) for
// Surface.shader: the web's GLSL in HLSL, three's frame throughout, the material's _Paving (course, wear, tone, turn).
#ifndef HIRAETH_PAVING_INCLUDED
#define HIRAETH_PAVING_INCLUDED
${s}
#endif
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(PAVING_HLSL_PATH, pavingHlsl());
  console.log(PAVING_HLSL_PATH);
}
