// The foes' painted surfaces for the Unity port's Surface shader (issue #264): src/foe-surface.js FOE_SURFACE_GLSL, the very
// GLSL the web draws, turned into HLSL and written to unity/Hiraeth/Assets/Hiraeth/Shaders/FoeSurface.hlsl, which
// Surface.shader's HIRAETH_FIGHT variant includes. Each feature's #ifdef FS_* becomes a branch on the material's _FoeBits (the
// web compiles a material's features only; here one program draws them all, each taken or skipped by the material, a
// uniform branch); its uniforms are the material's _SkinData slots (engine/foe-pack.js FOE_LAYOUT). tests/engine-unity.test.js
// checks the file is what this makes of the current GLSL.
//   node scripts/unity-export/foe-hlsl.mjs          (writes it)
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { FOE_SURFACE_GLSL, FOE_SURFACE_FEATURES } from '../../src/foe-surface.js';
import { FOE_LAYOUT } from '../../engine/foe-pack.js';
import { calls, RESERVED } from './skin-hlsl.mjs';

export const FOE_HLSL_PATH = fileURLToPath(new URL('../../unity/Hiraeth/Assets/Hiraeth/Shaders/FoeSurface.hlsl', import.meta.url));

// the surface shader's own names the GLSL reads, as the port has them (Surface.shader sets the fs* statics before the calls)
const HOST = { vObjPos: 'fsObjPos', vObjNormal: 'fsObjNormal', vWorldPos: 'fsWorldPos', vNormal: 'fsNormal', gl_FrontFacing: 'fsFront',
  cameraPosition: 'toThree(_WorldSpaceCameraPos)', uTime: '_MTime', uWearLite: '_WearLite', uSunDir: '_SunDir' };

/** FOE_SURFACE_GLSL in HLSL. */
export function foeHlsl(glsl = FOE_SURFACE_GLSL) {
  let s = glsl.replace(/^\s*#ifdef FOE_SURFACE\s*\n/, '').replace(/\n\s*#endif\s*$/, '\n');
  if (/#ifdef FOE_SURFACE|#ifndef|#if /.test(s)) throw new Error('foe-hlsl: an #if the converter does not know');
  // each feature: a branch on the material's bits (none nested)
  s = s.replace(/#ifdef FS_(\w+)([\s\S]*?)#endif/g, (m, k, body) => {
    const i = FOE_SURFACE_FEATURES.indexOf(k.toLowerCase());
    if (i < 0) throw new Error(`foe-hlsl: FS_${k} is no feature`);
    return `UNITY_BRANCH if (fsHas(${i})) {   // FS_${k}${body}}`;
  });
  if (/#/.test(s)) throw new Error('foe-hlsl: a preprocessor line left');
  // a vector made of one number: HLSL's constructors want every component
  for (const t of ['vec2', 'vec3', 'vec4', 'uvec4']) s = calls(s, t, (a) => (a.length === 1 ? `((${t})(${a[0]}))` : `${t}(${a.join(', ')})`));
  s = calls(s, 'atan', (a) => (a.length === 2 ? `atan2(${a[0]}, ${a[1]})` : `atan(${a[0]})`));
  s = calls(s, 'mod', (a) => `fsMod(${a[0]}, ${a[1]})`);
  s = s.replace(/\buvec([234])\b/g, 'uint$1').replace(/\bvec([234])\b/g, 'float$1')
    .replace(/\bmix\s*\(/g, 'lerp(').replace(/\bfract\s*\(/g, 'frac(').replace(/\bdFdx\s*\(/g, 'ddx(').replace(/\bdFdy\s*\(/g, 'ddy(')
    .replace(/\bfloatBitsToUint\s*\(/g, 'asuint(');
  // the uniforms: the material's slots
  for (const e of FOE_LAYOUT) {
    const at = `_SkinData[${e.slot}]`;
    const v = e.type === 'float' ? `${at}.x` : e.type === 'vec2' ? `${at}.xy` : e.type === 'vec3' ? `${at}.xyz` : at;
    s = s.replace(new RegExp(`\\b${e.name}\\b`, 'g'), `(${v})`);
  }
  for (const [k, v] of Object.entries(HOST)) s = s.replace(new RegExp(`\\b${k}\\b`, 'g'), v);
  // (HLSL's reserved words renamed, outside the comments)
  s = s.split('\n').map((l) => { const c = l.indexOf('//'), code = c < 0 ? l : l.slice(0, c); return code.replace(/\b\w+\b/g, (w) => (RESERVED.has(w) ? `${w}_` : w)) + (c < 0 ? '' : l.slice(c)); }).join('\n');
  if (/\bu[A-Z]\w*/.test(s.replace(/\buint\d?\b|\bunroll\b/g, ''))) throw new Error(`foe-hlsl: a uniform left: ${s.match(/\bu[A-Z]\w*/)[0]}`);
  return `// GENERATED by scripts/unity-export/foe-hlsl.mjs from src/foe-surface.js FOE_SURFACE_GLSL: do not edit.
// The foes' painted surfaces (bellies, mottling, rust, grain, bands, scales, spots, rivets, drips, cracks, glow, gloss) for
// Surface.shader's HIRAETH_FIGHT variant: each feature the web's own GLSL in HLSL, taken where the material's _FoeBits has it,
// its uniforms the material's _SkinData slots (engine/foe-pack.js), three's frame throughout.
#ifndef HIRAETH_FIGHT_SURFACE_INCLUDED
#define HIRAETH_FIGHT_SURFACE_INCLUDED

StructuredBuffer<float4> _SkinData;   // the material's uniforms packed (engine/foe-pack.js foePack; the skins' buffer, never both)
// (set by Surface.shader before foeSurface and foeGloss: the web's varyings)
static float3 fsObjPos, fsObjNormal, fsWorldPos, fsNormal;
static bool fsFront;
bool fsHas(int k) { return ((((uint)(_FoeBits + 0.5)) >> k) & 1u) != 0u; }
float fsMod(float x, float y) { return x - y * floor(x / y); }
${s}
#endif
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(FOE_HLSL_PATH, foeHlsl());
  console.log(FOE_HLSL_PATH);
}
