// The garden beds for the Unity port's Surface shader (issue #691): src/garden-beds-shader.js BEDS_GLSL, the very GLSL the
// web draws, turned into HLSL and written to unity/Hiraeth/Assets/Hiraeth/Shaders/GardenBeds.hlsl, which Surface.shader
// includes and calls on a bed's upward faces (its _Beds: row, turn, plants, on). tests/garden-beds.test.js checks the file
// is what this makes of the current GLSL.
//   node scripts/unity-export/beds-hlsl.mjs          (writes it)
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { BEDS_GLSL } from '../../src/garden-beds-shader.js';
import { glslChunkToHlsl } from './paving-hlsl.mjs';

export const BEDS_HLSL_PATH = fileURLToPath(new URL('../../unity/Hiraeth/Assets/Hiraeth/Shaders/GardenBeds.hlsl', import.meta.url));

const HOST = { uBeds: '_Beds', uPixelRatio: '_PixelRatio', uWearLite: '_WearLite' };

/** BEDS_GLSL in HLSL. */
export function bedsHlsl(glsl = BEDS_GLSL) {
  return `// GENERATED by scripts/unity-export/beds-hlsl.mjs from src/garden-beds-shader.js BEDS_GLSL: do not edit.
// Garden beds and tilled soil (issue #691: furrows, plants along the ridges, dry patches, pebbles) for Surface.shader: the
// web's GLSL in HLSL, three's frame throughout, the material's _Beds (row, turn, plants, on).
#ifndef HIRAETH_GARDEN_BEDS_INCLUDED
#define HIRAETH_GARDEN_BEDS_INCLUDED
${glslChunkToHlsl(glsl, HOST, 'beds-hlsl')}
#endif
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(BEDS_HLSL_PATH, bedsHlsl());
  console.log(BEDS_HLSL_PATH);
}
