// The surface marks of issue #669 for the Unity port's Surface shader: src/surface-marks.js (interiors, sheet-metal walls,
// worked timber, the ground's middle distance), the very GLSL the web draws, turned into HLSL and written to
// unity/Hiraeth/Assets/Hiraeth/Shaders/SurfaceMarks.hlsl, which Surface.shader includes and calls in uniform branches on
// the material's _Interior, _Sheet, _Timber and _GroundMid. tests/surface-marks.test.js checks it is current.
//   node scripts/unity-export/marks-hlsl.mjs          (writes it)
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { MARKS_GLSL } from '../../src/surface-marks.js';
import { glslChunkToHlsl } from './paving-hlsl.mjs';

export const MARKS_HLSL_PATH = fileURLToPath(new URL('../../unity/Hiraeth/Assets/Hiraeth/Shaders/SurfaceMarks.hlsl', import.meta.url));

const HOST = { uInteriorDado: '_InteriorDado', uInteriorSkirt: '_InteriorSkirt', uInterior: '_Interior', uSheet: '_Sheet', uTimber: '_Timber', uGroundMid: '_GroundMid',
  uPixelRatio: '_PixelRatio', uWearLite: '_WearLite' };

/** MARKS_GLSL in HLSL. */
export function marksHlsl(chunks = MARKS_GLSL) {
  const s = chunks.map((c) => glslChunkToHlsl(c, HOST, 'marks-hlsl')).join('\n');
  return `// GENERATED by scripts/unity-export/marks-hlsl.mjs from src/surface-marks.js: do not edit.
// The surface marks after the picked sheets (issue #669: interiors, sheet-metal walls, worked timber, the ground's middle
// distance) for Surface.shader: the web's GLSL in HLSL, three's frame throughout, the material's _Interior,
// _InteriorDado, _InteriorSkirt, _Sheet, _Timber and _GroundMid.
#ifndef HIRAETH_SURFACE_MARKS_INCLUDED
#define HIRAETH_SURFACE_MARKS_INCLUDED
${s}
#endif
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(MARKS_HLSL_PATH, marksHlsl());
  console.log(MARKS_HLSL_PATH);
}
