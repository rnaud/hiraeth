// The coral-shirt traveller's drawn face for the Unity port's Surface shader: src/characters/tripo-face.js
// TRIPO_FACE_GLSL turned into HLSL (the same constants, the same steps), written to
// unity/Memento/Assets/Memento/Shaders/TripoFace.hlsl. tests/engine-unity.test.js checks the file is what this
// makes of the current GLSL, so the two can't drift apart.
//   node scripts/unity-export/tripo-face-hlsl.mjs          (writes it)
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { TRIPO_FACE_GLSL } from '../../src/characters/tripo-face.js';

export const TRIPO_FACE_HLSL_PATH = fileURLToPath(new URL('../../unity/Memento/Assets/Memento/Shaders/TripoFace.hlsl', import.meta.url));

/** GLSL (this one's plain subset: vectors, mix, smoothstep, step, sign) to HLSL. */
export function tripoFaceHlsl(glsl = TRIPO_FACE_GLSL) {
  let s = glsl
    .replace(/\buniform vec4 (uTf\w+);[^\n]*\n/g, 'float4 _$1;\n')
    .replace(/\buTf(\w+)/g, (m, k) => `Tf${k}`)
    .replace(/_uTf/g, '_Tf')
    .replace(/\bTf(BrowA|BrowB|Eye|Mouth)\b/g, '_Tf$1')
    .replace(/\bvec([234])\b/g, 'float$1')
    .replace(/\bmix\(/g, 'lerp(')
    .replace(/\bconst float3 INK\b/g, 'static const float3 INK')
    .replace(/\binside\b/g, 'insideM')
    .replace(/\bline\b/g, 'lineY');
  return `// GENERATED by scripts/unity-export/tripo-face-hlsl.mjs from src/characters/tripo-face.js TRIPO_FACE_GLSL: do not edit.
// The coral-shirt traveller's drawn face (brows, eyes, mouth moved by his expression), in his body's bind space.
#ifndef MEMENTO_TRIPO_FACE_INCLUDED
#define MEMENTO_TRIPO_FACE_INCLUDED
${s}
#endif
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(TRIPO_FACE_HLSL_PATH, tripoFaceHlsl());
  console.log(TRIPO_FACE_HLSL_PATH);
}
