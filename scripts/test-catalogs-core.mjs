// Literal catalogues of source directories for tests (tests/catalogs/*.js), so the test selector sees what a test
// reads or imports instead of a directory listing it cannot follow (a test that lists a directory and imports or reads
// each entry ran on every commit). `node scripts/test-catalogs.mjs` writes them; tests/test-catalogs.test.js lists the
// same directories and fails when a catalogue is not exactly what this renders, so a new file can't be missed.
// Pure: no file system here (the command and the test list the directories).

/** name → { dir (from the repository root), recursive, match (of a path within dir), kind: 'import' | 'source' }. */
export const SPECS = {
  'story-modules': { dir: 'src/story', recursive: false, match: /\.js$/, kind: 'import' },
  'story-data-modules': { dir: 'src/story', recursive: false, match: /-(?:data|people)\.js$/, kind: 'import' },
  'story-sources': { dir: 'src/story', recursive: false, match: /\.js$/, kind: 'source' },
  'temples-data-modules': { dir: 'src/temples', recursive: false, match: /-(?:data|people)\.js$/, kind: 'import' },
  'temples-sources': { dir: 'src/temples', recursive: false, match: /\.js$/, kind: 'source' },
  'levels-sources': { dir: 'src/levels', recursive: false, match: /\.js$/, kind: 'source' },
  'gadgets-sources': { dir: 'src/gadgets', recursive: false, match: /\.js$/, kind: 'source' },
  'src-sources': { dir: 'src', recursive: true, match: /\.(?:js|css|html)$/, kind: 'source' },
  'engine-sources': { dir: 'engine', recursive: true, match: /\.m?js$/, kind: 'source' },
};

/** The entries a catalogue holds, from a directory listing (names, or paths within it for a recursive one). */
export function entries(name, listing) {
  const { match } = SPECS[name];
  return [...new Set(listing.map((f) => String(f).split('\\').join('/')))].filter((f) => match.test(f)).sort();
}

/** The catalogue's whole text for these entries. */
export function renderCatalog(name, files) {
  const { dir, recursive, match, kind } = SPECS[name];
  const q = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
  const at = (f) => q(`../../${dir}/${f}`);
  const head = [
    `// Generated by \`node scripts/test-catalogs.mjs\` (${name}, scripts/test-catalogs-core.mjs): every file of ${dir}/${recursive ? ' and below' : ''}`,
    `// matching ${match}. Don't edit: tests/test-catalogs.test.js fails when this and the directory differ.`,
  ];
  if (kind === 'import') return [...head,
    'const loaders = {',
    ...files.map((f) => `  ${q(f)}: () => import(${at(f)}),`),
    '};',
    'export const files = Object.freeze(Object.keys(loaders));',
    '/** The module of one entry (a path within the directory, as listed in `files`). */',
    'export function load(name) {',
    `  if (!Object.hasOwn(loaders, name)) throw Error(\`\${name}: not in ${dir}/ (node scripts/test-catalogs.mjs)\`);`,
    '  return loaders[name]();',
    '}',
    ''].join('\n');
  return [...head,
    "import { readFileSync } from 'node:fs';",
    'const readers = {',
    ...files.map((f) => `  ${q(f)}: () => readFileSync(new URL(${at(f)}, import.meta.url), 'utf8'),`),
    '};',
    'export const files = Object.freeze(Object.keys(readers));',
    '/** The text of one entry (a path within the directory, as listed in `files`). */',
    'export function source(name) {',
    `  if (!Object.hasOwn(readers, name)) throw Error(\`\${name}: not in ${dir}/ (node scripts/test-catalogs.mjs)\`);`,
    '  return readers[name]();',
    '}',
    ''].join('\n');
}
