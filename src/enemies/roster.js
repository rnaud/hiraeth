export const ENEMY_BY_ID = Object.fromEntries(ENEMY_ROSTER.map(e => [e.id, e]));
export const WORLD_ENEMIES = Object.fromEntries([...new Set(ENEMY_ROSTER.map(e => e.world))].map(w => [w, ENEMY_ROSTER.filter(e => e.world === w)]));

/** Early encounters introduce creatures, then all four designs recur; development waves retain their original roster. */
export function worldPack(n, world) {
  const r = WORLD_ENEMIES[world];
  if (!r) return null;
  if (!n) return [r[0].id];
  const patterns = [[1, 0], [2, 0], [3, 1], [0, 1], [2, 3]];
  return patterns[(n - 1) % patterns.length].map(i => r[i].id);
}
